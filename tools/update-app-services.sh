#!/usr/bin/env bash
# Moves rust/oganesson_sync to another application-services release:
#   tools/update-app-services.sh v159.0
# Pins the tag's commit in Cargo.toml and Cargo.lock, regenerates the places
# metrics that glean-build stands in for, and updates the version strings.
# Then build (tools/build-sync-lib.sh) and fix what the new API breaks.
# Needs git, cargo, curl and pipx.
set -euo pipefail

tag="$1"
repo=https://github.com/mozilla/application-services
raw=https://raw.githubusercontent.com/mozilla
crate="$(dirname "$(realpath "$0")")/../rust/oganesson_sync"

# The peeled commit if the tag is annotated, else the tag's own.
rev="$(git ls-remote "$repo" "refs/tags/$tag" "refs/tags/$tag^{}" | tail -1 | cut -f1)"
[ -n "$rev" ] || { echo "no tag $tag in $repo" >&2; exit 1; }
old_rev="$(grep -om1 'rev = "[0-9a-f]*"' "$crate/Cargo.toml" | cut -d'"' -f2)"
old_tag="$(grep -om1 'application-services v[0-9.]*' "$crate/src/lib.rs" | cut -d' ' -f2)"
echo "application-services $old_tag ($old_rev) -> $tag ($rev)"

sed -i "s/$old_rev/$rev/g" "$crate/Cargo.toml"
# What glean-build would generate: places' metrics.yaml through the
# glean_parser that places' pinned Glean asks for.
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
curl -sfL "$raw/application-services/$tag/components/places/metrics.yaml" -o "$tmp/metrics.yaml"
glean_tag="$(curl -sfL "$raw/application-services/$tag/components/places/Cargo.toml" |
    sed -n 's/^glean-build = .*tag = "\([^"]*\)".*/\1/p')"
parser="$(curl -sfL "$raw/glean/$glean_tag/glean-core/build/src/lib.rs" |
    sed -n 's/^const GLEAN_PARSER_VERSION: &str = "\(.*\)";/\1/p')"
[ -n "$parser" ] || { echo "can't find glean_parser version for Glean $glean_tag" >&2; exit 1; }
pipx run --spec "glean_parser~=$parser" glean_parser translate \
    --output "$tmp/out" --format rust_sym "$tmp/metrics.yaml"
{
    echo "// Pre-generated by glean_parser $parser (\`translate --format rust_sym\`) from"
    echo "// application-services $tag components/places/metrics.yaml. Regenerate it"
    echo "// with tools/update-app-services.sh. See ../src/lib.rs."
    echo
    cat "$tmp/out/glean_metrics.rs"
} > "$crate/glean-build/src/places_metrics.rs"
sed -i "s/^version = .*/version = \"$parser\"/" "$crate/glean-build/Cargo.toml"

sed -i "s/application-services $old_tag/application-services $tag/g" \
    "$crate/src/lib.rs" "$crate/../../docs/firefox-sync.md"
sed -i "s/crates at $old_tag/crates at $tag/" "$crate/../../docs/firefox-sync.md"

# Re-resolves only what the new rev needs; other crates keep their versions.
cargo fetch --manifest-path "$crate/Cargo.toml"

git -C "$crate" diff --stat -- . ../../docs
echo "Upstream changes: $repo/compare/$old_rev...$rev"
